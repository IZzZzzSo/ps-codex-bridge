import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile, writeFile, stat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import http from 'node:http';
import { createServer } from '../bridge/server.mjs';
import { encodePNG, decodePNG } from '../bridge/png.mjs';

test('PNG roundtrip preserves exact RGBA including fully transparent color', () => {
  const rgba = Buffer.from([10, 20, 30, 0, 40, 50, 60, 128, 255, 240, 230, 255, 0, 0, 0, 255]);
  const png = encodePNG(2, 2, rgba);
  assert.deepEqual(decodePNG(png), { width: 2, height: 2, rgba });
  const bad = Buffer.from(png); bad[30] ^= 1; assert.throws(() => decodePNG(bad), /校验/);
  assert.throws(() => encodePNG(8000, 8000, Buffer.alloc(0)), /1600/);
});
test('authenticated capture → actual macOS normalization → masked return and acknowledgement', async t => {
  const runtime = await mkdtemp(path.join(tmpdir(), 'ps-codex-test-'));
  const { server, store } = await createServer({ runtime, port: 0 });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await rm(runtime, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`, token = store.config.token;
  const request = async (route, method = 'GET', body, auth = true) => {
    const binary = Buffer.isBuffer(body);
    const response = await fetch(base + route, { method, headers: { ...(auth ? { Authorization: `Bearer ${token}` } : {}), ...(body === undefined ? {} : { 'Content-Type': binary ? 'application/octet-stream' : 'application/json' }) }, body: body === undefined ? undefined : binary ? body : JSON.stringify(body) });
    return { status: response.status, body: await response.json() };
  };
  assert.equal((await request('/health', 'GET', undefined, false)).status, 200);
  assert.equal((await request('/v1/jobs', 'GET', undefined, false)).status, 401);
  const blockedStatus = await new Promise((resolve, reject) => {
    const req = http.get(base + '/health', { headers: { Host: 'evil.example' } }, res => { res.resume(); resolve(res.statusCode); }); req.on('error', reject);
  }); assert.equal(blockedStatus, 403);
  const input = { sessionId: 'test-session-1234', mode: 'selection', document: { id: 5, name: '测试.psd', width: 10, height: 10 }, bounds: { left: 3, top: 4, right: 5, bottom: 6 }, prompt: '保持位置，修改背景', pixels: Buffer.from([1, 2, 3, 255, 4, 5, 6, 255, 7, 8, 9, 255, 10, 11, 12, 128]).toString('base64'), selectionMask: Buffer.from([255, 128, 0, 255]).toString('base64') };
  assert.equal((await request('/v1/jobs', 'POST', { ...input, pixels: 'bad' })).status, 409);
  const created = await request('/v1/jobs', 'POST', input); assert.equal(created.status, 201);
  const { job, desktopLink } = created.body;
  assert.equal(new URL(desktopLink).protocol, 'codex:');
  assert.equal(new URL(desktopLink).searchParams.get('path'), runtime);
  assert.ok((await readFile(path.join(store.dir(job.id), 'request.md'), 'utf8')).includes(':codex-followup[回传 PS]'));
  assert.deepEqual(decodePNG(await readFile(path.join(store.dir(job.id), 'input.png'))).rgba, Buffer.from(input.pixels, 'base64'));
  assert.equal((await stat(path.join(runtime, 'connection.json'))).mode & 0o777, 0o600);
  const src = path.join(runtime, 'source.png');
  await writeFile(src, encodePNG(4, 4, Buffer.from(Array.from({ length: 16 }, () => [90, 100, 110, 255]).flat())));
  const jpeg = path.join(runtime, 'source.jpg'); execFileSync('/usr/bin/sips', ['-s', 'format', 'jpeg', src, '--out', jpeg]);
  const prepared = await request(`/v1/jobs/${job.id}/result`, 'POST', await readFile(jpeg));
  assert.equal(prepared.status, 200, JSON.stringify(prepared.body));
  assert.equal(prepared.body.job.state, 'ready'); assert.equal(prepared.body.job.revision, 1);
  const result = decodePNG(await readFile(path.join(store.dir(job.id), 'result-1.png')));
  assert.equal(result.width, 2); assert.equal(result.height, 2);
  assert.deepEqual([result.rgba[3], result.rgba[7], result.rgba[11], result.rgba[15]], [255, 128, 0, 255]);
  assert.ok(Math.abs(result.rgba[0] - 90) < 8);
  assert.equal((await request(`/v1/jobs/${job.id}/queue`, 'POST', { revision: 0 })).status, 409);
  assert.equal((await request(`/v1/jobs/${job.id}/queue`, 'POST', { revision: 1 })).body.job.state, 'queued');
  assert.equal((await request(`/v1/jobs/${job.id}/claim`, 'POST', { revision: 1, sessionId: 'wrong-session' })).status, 409);
  const claims = await Promise.all([1, 2].map(() => request(`/v1/jobs/${job.id}/claim`, 'POST', { revision: 1, sessionId: input.sessionId })));
  assert.deepEqual(claims.map(c => c.status).sort(), [200, 409]);
  const lease = claims.find(c => c.status === 200).body.job.lease;
  const pixels = await fetch(base + `/v1/jobs/${job.id}/pixels`, { headers: { Authorization: 'Bearer ' + token } });
  assert.deepEqual(Buffer.from(await pixels.arrayBuffer()), result.rgba);
  assert.equal((await request(`/v1/jobs/${job.id}/complete`, 'POST', { revision: 1, lease: 'wrong' })).status, 409);
  assert.equal((await request(`/v1/jobs/${job.id}/fail`, 'POST', { revision: 1, lease, error: 'PS busy' })).body.job.state, 'ready');
  await request(`/v1/jobs/${job.id}/queue`, 'POST', { revision: 1 });
  const retry = await request(`/v1/jobs/${job.id}/claim`, 'POST', { revision: 1, sessionId: input.sessionId });
  const complete = { revision: 1, lease: retry.body.job.lease, layerId: 99 };
  assert.equal((await request(`/v1/jobs/${job.id}/complete`, 'POST', complete)).body.job.state, 'applied');
  assert.equal((await request(`/v1/jobs/${job.id}/complete`, 'POST', complete)).status, 200);
  assert.equal((await request(`/v1/jobs/${job.id}/queue`, 'POST', { revision: 1 })).status, 409);
  const transparent = encodePNG(2, 2, Buffer.from([40, 50, 60, 128, 70, 80, 90, 128, 0, 0, 0, 255, 10, 20, 30, 0]));
  const next = await request(`/v1/jobs/${job.id}/result`, 'POST', transparent);
  assert.equal(next.status, 200); assert.equal(next.body.job.revision, 2);
  const nextImage = decodePNG(await readFile(path.join(store.dir(job.id), 'result-2.png')));
  assert.deepEqual([nextImage.rgba[3], nextImage.rgba[7], nextImage.rgba[11], nextImage.rgba[15]], [128, 64, 0, 0]);
  assert.equal((await request(`/v1/jobs/${job.id}/result`, 'POST', Buffer.from('not an image'))).status, 409);
  assert.equal((await request(`/v1/jobs/${job.id}`)).body.job.revision, 2);
  await request(`/v1/jobs/${job.id}/queue`, 'POST', { revision: 2 });
  const invalidTarget = await request(`/v1/jobs/${job.id}/fail`, 'POST', { revision: 2, sessionId: input.sessionId, error: '文档已关闭' });
  assert.equal(invalidTarget.body.job.state, 'ready');
  assert.equal((await request('/v1/jobs')).body.jobs.length, 1);
});
